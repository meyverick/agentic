#!/usr/bin/env bun
/** funding-gate — generates and verifies .github/FUNDING.yml + DEPENDENCIES.md from manifests. */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join } from "node:path";

import type { Dep } from "./funding-sources.ts";
import { digest, httpStatus, mapLimit, parseManifests, repoOwner, resolve } from "./funding-sources.ts";

export const ALLOWED_KEYS = ["github", "thanks_dev", "custom"];
const GENERATOR = "skills/check/scripts/funding-gate.ts";
const USAGE = `usage: funding-gate.ts --write|--check [--verify-links] <repo-dir>`;

/** Links that always appear in `custom:`, independent of the dependency set. */
export function baselineLinks(owner: string): string[] {
  return owner
    ? [`https://github.com/sponsors/${owner}`, `https://thanks.dev/u/gh/${owner}`]
    : ["https://thanks.dev"];
}

export async function render(repoDir: string, deps: Dep[]): Promise<[string, string]> {
  const owner = repoOwner(repoDir);
  const marker = digest(deps);
  const lines = [
    `# Generated by ${GENERATOR} --write -- never hand-edit.`,
    "# GitHub renders at most 4 GitHub Sponsors entries and 4 custom URLs; this file is the",
    "# full machine-readable dependency-funding ledger, so the tail beyond the render window",
    "# is kept for other consumers (Forgejo, thanks.dev) and for CREDITS.md parity.",
    `# deps-sha256: ${marker}`,
    owner ? `github: [${owner}]` : "github: []",
    owner ? `thanks_dev: u/gh/${owner}` : "# thanks_dev: u/gh/<owner>",
    "custom:",
    ...baselineLinks(owner).map((url) => `  - "${url}"`),
  ];
  const credits = [
    "# Dependencies",
    "",
    "Every dependency this repository declares, with its upstream funding link.",
    `Support the whole tree at once via [thanks.dev](https://thanks.dev/u/gh/${owner}).`,
    "",
    `deps-sha256: ${marker}`,
    "",
    "| Ecosystem | Package | Funding |",
    "| --- | --- | --- |",
  ];

  for (const [ecosystem, name] of deps) {
    const urls = await resolve(ecosystem, name);
    credits.push(`| ${ecosystem} | ${name} | ${urls[0] ?? "no public funding link"} |`);
    for (const url of urls) lines.push(`  - "${url}"`);
  }

  return [`${lines.join("\n")}\n`, `${credits.join("\n")}\n`];
}

export interface FundingParse {
  values: Record<string, string>;
  urls: string[];
  problems: string[];
}

export function parseFunding(text: string): FundingParse {
  const values: Record<string, string> = {};
  const urls: string[] = [];
  const problems: string[] = [];
  let section = "";

  text.split("\n").forEach((raw, index) => {
    const line = raw.trim();
    if (!line || line.startsWith("#")) return;
    const header = /^([A-Za-z0-9_]+)\s*:\s*(.*)$/.exec(line);
    if (header && !raw.startsWith(" ") && !raw.startsWith("\t")) {
      const [, key, value] = header;
      section = key;
      values[key] = value.trim();
      if (!ALLOWED_KEYS.includes(key)) problems.push(`line ${index + 1}: unsupported key '${key}'`);
      if (key === "custom" && value.trim()) {
        problems.push(`line ${index + 1}: 'custom' must be a block list, not '${value.trim()}'`);
      }
      return;
    }
    if (section === "custom" && line.startsWith("- ")) {
      urls.push(line.slice(2).trim().replace(/^['"]|['"]$/g, ""));
      return;
    }
    problems.push(`line ${index + 1}: unexpected content '${line}'`);
  });

  return { values, urls, problems };
}

export function dependencyRows(text: string): Array<[string, string, string]> {
  const rows: Array<[string, string, string]> = [];
  for (const line of text.split("\n")) {
    const cells = line.trim().replace(/^\|/, "").replace(/\|$/, "").split("|").map((cell) => cell.trim());
    if (cells.length === 3 && cells[0] !== "Ecosystem" && new Set(cells[0]).size !== 1) {
      rows.push([cells[0], cells[1], cells[2]]);
    }
  }
  return rows;
}

export async function validate(repoDir: string, deps: Dep[], warn: (line: string) => void): Promise<string[]> {
  const owner = repoOwner(repoDir);
  const funding = await readFile(join(repoDir, ".github", "FUNDING.yml"), "utf8");
  const parsed = parseFunding(funding);
  const problems = [...parsed.problems];

  if (owner) {
    const declared = (parsed.values.github ?? "").replace(/^\[|\]$/g, "").split(",");
    if (declared.map((name) => name.trim()).filter(Boolean).join(",") !== owner) {
      problems.push(`github must be exactly [${owner}], found ${JSON.stringify(parsed.values.github)}`);
    }
    if (parsed.values.thanks_dev !== `u/gh/${owner}`) {
      problems.push(`thanks_dev must be u/gh/${owner}, found ${JSON.stringify(parsed.values.thanks_dev)}`);
    }
  } else if ((parsed.values.github ?? "[]") !== "[]") {
    problems.push("github must be empty when the repository owner cannot be resolved");
  }

  const missingBaseline = baselineLinks(owner).filter((url) => !parsed.urls.includes(url));
  if (missingBaseline.length > 0) {
    problems.push(`custom must list the baseline support links, missing ${JSON.stringify(missingBaseline)}`);
  }
  const badScheme = parsed.urls.filter((url) => !url.startsWith("https:") || !URL.canParse(url));
  if (badScheme.length > 0) problems.push(`custom URLs must be https: ${JSON.stringify(badScheme.slice(0, 3))}`);
  const duplicates = [...new Set(parsed.urls.filter((url) => parsed.urls.filter((other) => other === url).length > 1))].sort();
  if (duplicates.length > 0) problems.push(`duplicate custom URLs: ${JSON.stringify(duplicates.slice(0, 3))}`);

  const rows = dependencyRows(await readFile(join(repoDir, "DEPENDENCIES.md"), "utf8"));
  const listed = new Set(rows.map(([ecosystem, name]) => `${ecosystem}:${name}`));
  const declared = new Set(deps.map(([ecosystem, name]) => `${ecosystem}:${name}`));
  if (listed.size !== declared.size || [...declared].some((entry) => !listed.has(entry))) {
    const missing = [...declared].filter((entry) => !listed.has(entry)).sort().slice(0, 5);
    const extra = [...listed].filter((entry) => !declared.has(entry)).sort().slice(0, 5);
    problems.push(`DEPENDENCIES.md rows do not match manifests (missing=${JSON.stringify(missing)}, extra=${JSON.stringify(extra)})`);
  }

  const linked = rows.filter(([, , link]) => link.startsWith("http")).length + baselineLinks(owner).length;
  if (owner && parsed.urls.length !== linked) {
    problems.push(`custom has ${parsed.urls.length} URLs but DEPENDENCIES.md implies ${linked}`);
  }

  const readme = join(repoDir, "README.md");
  if (existsSync(readme) && !(await readFile(readme, "utf8")).includes("thanks.dev")) {
    problems.push("README.md must name the thanks.dev support link");
  }
  const contributing = join(repoDir, "CONTRIBUTING.md");
  if (existsSync(contributing)) {
    if (!(await readFile(contributing, "utf8")).includes("thanks.dev")) {
      problems.push("CONTRIBUTING.md must name the thanks.dev support link");
    }
  } else {
    warn("funding-gate: WARN CONTRIBUTING.md absent (account-level default expected)");
  }

  return problems;
}

export async function verifyLinks(repoDir: string, warn: (line: string) => void): Promise<string[]> {
  const owner = repoOwner(repoDir);
  const parsed = parseFunding(await readFile(join(repoDir, ".github", "FUNDING.yml"), "utf8"));
  const targets: Array<[string, string]> = parsed.urls.map((url) => [url, url]);
  if (owner) {
    targets.push([`github:${owner}`, `https://github.com/${owner}`]);
    targets.push([`thanks_dev:u/gh/${owner}`, `https://thanks.dev/u/gh/${owner}`]);
  }

  const problems: string[] = [];
  const statuses = await mapLimit(targets, 8, async ([label, url]) => [label, await httpStatus(url)] as const);
  for (const [label, status] of statuses) {
    if (status === 0 || status === 404 || status === 410 || status >= 500) {
      problems.push(`${label}: does not resolve (status ${status || "unreachable"})`);
    } else if ([401, 403, 429].includes(status)) {
      warn(`funding-gate: WARN ${label}: unverified (status ${status}, anti-bot wall)`);
    }
  }
  return problems;
}

export async function main(argv: string[]): Promise<number> {
  const flags = argv.filter((arg) => arg.startsWith("--"));
  const rest = argv.filter((arg) => !arg.startsWith("--"));
  const known = ["--write", "--check"];
  if (rest.length !== 1 || flags.length === 0 || !known.includes(flags[0])) {
    console.error(USAGE);
    return 2;
  }
  const unknown = flags.slice(1).filter((flag) => flag !== "--verify-links");
  if (unknown.length > 0 || flags.length > 2) {
    console.error(`usage: unknown flags ${JSON.stringify(unknown)}`);
    return 2;
  }

  const [mode] = flags;
  const repoDir = rest[0];
  const verify = flags.includes("--verify-links");
  const deps = await parseManifests(repoDir);

  if (mode === "--write") {
    const [funding, credits] = await render(repoDir, deps);
    await mkdir(join(repoDir, ".github"), { recursive: true });
    await writeFile(join(repoDir, ".github", "FUNDING.yml"), funding);
    await writeFile(join(repoDir, "DEPENDENCIES.md"), credits);
    console.log(`funding-gate: wrote ${deps.length} dependencies`);
    return 0;
  }

  const marker = `deps-sha256: ${digest(deps)}`;
  const problems: string[] = [];
  for (const rel of [join(".github", "FUNDING.yml"), "DEPENDENCIES.md"]) {
    const path = join(repoDir, rel);
    if (!existsSync(path)) problems.push(`${rel}: missing (run funding-gate.ts --write)`);
    else if (!(await readFile(path, "utf8")).includes(marker)) {
      problems.push(`${rel}: stale, manifests changed (run funding-gate.ts --write)`);
    }
  }

  const warn = (line: string): void => console.error(line);
  const failed = problems.length > 0 ? problems : await validate(repoDir, deps, warn);
  const all = failed.length > 0 || !verify ? failed : await verifyLinks(repoDir, warn);
  for (const problem of all) console.error(`funding-gate: FAIL ${problem}`);
  return all.length > 0 ? 1 : 0;
}

const meta = import.meta as ImportMeta & { main?: boolean };
if (meta.main) {
  process.exitCode = await main(process.argv.slice(2));
}
